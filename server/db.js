/**
 * 서버 공용 데이터베이스 계층 (API 서버 + 실시간 서버가 함께 쓴다).
 *
 * 같은 코드로 세 가지 DB 를 쓴다.
 *  - SQLite  (기본, 로컬 개발)      : DB_PATH 파일. Node 내장 node:sqlite
 *  - Postgres (배포, Supabase 등)   : DATABASE_URL 이 있으면 사용. pg 연결 풀
 *  - PGlite  (자동 테스트 전용)     : DB_DRIVER=pglite. 메모리 안의 진짜 Postgres
 *
 * 쿼리 작성 규칙 (두 방언에서 똑같이 동작하도록):
 *  - 자리표시자는 `?` 로 쓴다. Postgres 에서는 $1, $2 … 로 바꿔 보낸다. (SQL 문자열 안에 ? 를 쓰지 말 것)
 *  - 새 행의 id 가 필요하면 `RETURNING id` 를 붙이고 get() 으로 받는다.
 *  - 중복 무시는 `ON CONFLICT DO NOTHING`, 개수는 `CAST(COUNT(*) AS INTEGER)` 처럼 표준 SQL 을 쓴다.
 *
 * 사용법: import { db } from '../db.js'
 *   await db.get(sql, [params])   → 한 행 또는 undefined
 *   await db.all(sql, [params])   → 행 배열
 *   await db.run(sql, [params])   → { changes }
 *   await db.tx(async (t) => { await t.run(...) })  → 하나의 트랜잭션 (실패 시 전부 되돌림)
 */
import { DB_PATH, DATABASE_URL, DB_DRIVER, databaseSslOptions, databaseUrlForPg } from './config.js'

