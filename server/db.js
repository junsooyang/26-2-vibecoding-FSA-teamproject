/** `?` 자리표시자를 Postgres 의 $1, $2 … 로 바꾼다. */
export function toPgPlaceholders(sql) {
  let i = 0
  return sql.replace(/\?/g, () => `$${++i}`)
}

function normalizeParams(params) {
  return (params ?? []).map((v) => (v === undefined ? null : v))
}

/** 행 객체를 평범한 객체로 (node:sqlite 는 프로토타입 없는 객체를 준다) */
const plain = (row) => (row ? { ...row } : undefined)

// ---------------------------------------------------------------------------
// SQLite
// ---------------------------------------------------------------------------

async function createSqliteDb(file) {
  const { DatabaseSync } = await import('node:sqlite')
  const conn = new DatabaseSync(file)
  // 개발 중에는 API·실시간 서버가 따로 떠서 같은 파일을 쓸 수 있으므로 잠금 대기 시간을 둔다.
  conn.exec('PRAGMA foreign_keys = ON; PRAGMA busy_timeout = 5000;')
  conn.exec(SQLITE_SCHEMA)
  // 예전 board.db 에는 여러 개의 개인 노트(notes_json) 칸이 없으므로 붙인다 (SQLite 는 IF NOT EXISTS 미지원)
  const personalCols = conn.prepare('PRAGMA table_info(personal_spaces)').all()
  if (!personalCols.some((c) => c.name === 'notes_json')) {
    conn.exec("ALTER TABLE personal_spaces ADD COLUMN notes_json TEXT NOT NULL DEFAULT '[]'")
  }

  const cache = new Map()
  const stmt = (sql) => {
    let s = cache.get(sql)
    if (!s) {
      s = conn.prepare(sql)
      cache.set(sql, s)
    }
    return s
  }
  const exec = {
    get: (sql, params) => plain(stmt(sql).get(...normalizeParams(params))),
    all: (sql, params) => stmt(sql).all(...normalizeParams(params)).map(plain),
    run: (sql, params) => ({ changes: Number(stmt(sql).run(...normalizeParams(params)).changes) }),
  }

  // 연결이 하나뿐이라, 트랜잭션 도중에 다른 요청의 쿼리가 끼어들지 않도록 잠금을 건다.
  let lock = Promise.resolve()
  async function waitUnlocked() {
    for (;;) {
      const current = lock
      await current
      if (current === lock) return // 그 사이 새 트랜잭션이 시작되지 않았음
    }
  }
  const outside = (fn) => async (sql, params) => {
    await waitUnlocked()
    return fn(sql, params)
  }

  return {
    dialect: 'sqlite',
    get: outside(exec.get),
    all: outside(exec.all),
    run: outside(exec.run),
    async tx(fn) {
      const prev = lock
      let release
      lock = new Promise((r) => (release = r))
      await prev
      const handle = {
        dialect: 'sqlite',
        get: async (s, p) => exec.get(s, p),
        all: async (s, p) => exec.all(s, p),
        run: async (s, p) => exec.run(s, p),
      }
      conn.exec('BEGIN')
      try {
        const result = await fn(handle)
        conn.exec('COMMIT')
        return result
      } catch (err) {
        conn.exec('ROLLBACK')
        throw err
      } finally {
        release()
      }
    },
    async close() {
      try {
        conn.close()
      } catch {
        // 이미 닫힘
      }
    },
  }
}

