const SQLITE_SCHEMA = `
  CREATE TABLE IF NOT EXISTS users (
    id            INTEGER PRIMARY KEY AUTOINCREMENT,
    username      TEXT UNIQUE NOT NULL,
    name          TEXT NOT NULL,
    password_hash TEXT NOT NULL,
    created_at    INTEGER NOT NULL
  );
  CREATE TABLE IF NOT EXISTS rooms (
    id          INTEGER PRIMARY KEY AUTOINCREMENT,
    slug        TEXT UNIQUE NOT NULL,
    name        TEXT NOT NULL,
    owner_id    INTEGER NOT NULL,
    created_at  INTEGER NOT NULL,
    FOREIGN KEY (owner_id) REFERENCES users(id) ON DELETE CASCADE
  );
  CREATE TABLE IF NOT EXISTS room_members (
    room_id   INTEGER NOT NULL,
    user_id   INTEGER NOT NULL,
    role      TEXT NOT NULL DEFAULT 'member',
    joined_at INTEGER NOT NULL,
    PRIMARY KEY (room_id, user_id),
    FOREIGN KEY (room_id) REFERENCES rooms(id) ON DELETE CASCADE,
    FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
  );
  CREATE INDEX IF NOT EXISTS idx_room_members_user ON room_members(user_id);
  CREATE TABLE IF NOT EXISTS personal_spaces (
    user_id    INTEGER NOT NULL,
    room_slug  TEXT NOT NULL,
    note       TEXT NOT NULL DEFAULT '',
    files_json TEXT NOT NULL DEFAULT '[]',
    updated_at INTEGER NOT NULL,
    notes_json TEXT NOT NULL DEFAULT '[]',
    PRIMARY KEY (user_id, room_slug),
    FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
  );
  CREATE TABLE IF NOT EXISTS files (
    id          TEXT PRIMARY KEY,
    room_slug   TEXT NOT NULL,
    name        TEXT NOT NULL,
    mime        TEXT NOT NULL,
    size        INTEGER NOT NULL,
    uploader_id INTEGER NOT NULL,
    created_at  INTEGER NOT NULL
  );
  CREATE INDEX IF NOT EXISTS idx_files_room ON files(room_slug);
  CREATE TABLE IF NOT EXISTS docs (
    name       TEXT PRIMARY KEY,
    state      BLOB NOT NULL,
    updated_at INTEGER NOT NULL
  );
`

/** Postgres 테이블 목록 (RLS 를 켤 대상) */
export const PG_TABLES = ['users', 'rooms', 'room_members', 'personal_spaces', 'files', 'docs']

// 시각(ms)은 32비트를 넘으므로 BIGINT. 바이너리는 BYTEA.
const PG_SCHEMA = `
  CREATE TABLE IF NOT EXISTS users (
    id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username      TEXT UNIQUE NOT NULL,
    name          TEXT NOT NULL,
    password_hash TEXT NOT NULL,
    created_at    BIGINT NOT NULL
  );
  CREATE TABLE IF NOT EXISTS rooms (
    id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug        TEXT UNIQUE NOT NULL,
    name        TEXT NOT NULL,
    owner_id    INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    created_at  BIGINT NOT NULL
  );
  CREATE TABLE IF NOT EXISTS room_members (
    room_id   INTEGER NOT NULL REFERENCES rooms(id) ON DELETE CASCADE,
    user_id   INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    role      TEXT NOT NULL DEFAULT 'member',
    joined_at BIGINT NOT NULL,
    PRIMARY KEY (room_id, user_id)
  );
  CREATE INDEX IF NOT EXISTS idx_room_members_user ON room_members(user_id);
  CREATE TABLE IF NOT EXISTS personal_spaces (
    user_id    INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    room_slug  TEXT NOT NULL,
    note       TEXT NOT NULL DEFAULT '',
    files_json TEXT NOT NULL DEFAULT '[]',
    updated_at BIGINT NOT NULL,
    notes_json TEXT NOT NULL DEFAULT '[]',
    PRIMARY KEY (user_id, room_slug)
  );
  -- 예전에 만든 표에는 여러 개의 개인 노트(notes_json) 칸이 없으므로 붙인다
  ALTER TABLE personal_spaces ADD COLUMN IF NOT EXISTS notes_json TEXT NOT NULL DEFAULT '[]';
  CREATE TABLE IF NOT EXISTS files (
    id          TEXT PRIMARY KEY,
    room_slug   TEXT NOT NULL,
    name        TEXT NOT NULL,
    mime        TEXT NOT NULL,
    size        BIGINT NOT NULL,
    uploader_id INTEGER NOT NULL,
    created_at  BIGINT NOT NULL
  );
  CREATE INDEX IF NOT EXISTS idx_files_room ON files(room_slug);
  CREATE TABLE IF NOT EXISTS docs (
    name       TEXT PRIMARY KEY,
    state      BYTEA NOT NULL,
    updated_at BIGINT NOT NULL
  );
  -- Supabase 는 public 스키마의 테이블을 자동 REST API(PostgREST)로 공개한다.
  -- RLS 를 켜고 정책을 두지 않으면 공개 키(anon/publishable)로는 어떤 행도 읽거나 쓸 수 없다.
  -- 우리 서버는 테이블 소유자로 접속하므로 영향을 받지 않는다.
  ${PG_TABLES.map((t) => `ALTER TABLE ${t} ENABLE ROW LEVEL SECURITY;`).join('\n  ')}
`

