/** pg 로 바이너리를 보낼 때는 Buffer 로 */
function toPgValue(v) {
  if (v === undefined) return null
  if (v instanceof Uint8Array && !Buffer.isBuffer(v)) return Buffer.from(v.buffer, v.byteOffset, v.byteLength)
  return v
}

async function createPostgresDb(url) {
  const pg = (await import('pg')).default
  // BIGINT(시각·개수)을 숫자로 받는다. ms 시각은 Number 로 안전하게 표현된다.
  pg.types.setTypeParser(20, (v) => (v === null ? null : Number(v)))

  const pool = new pg.Pool({
    connectionString: databaseUrlForPg(url),
    ssl: databaseSslOptions(url),
    max: Number(process.env.DATABASE_POOL_MAX) || 5,
    idleTimeoutMillis: 30_000,
    connectionTimeoutMillis: 10_000,
  })
  // 쉬고 있는 연결이 끊겨도 서버 프로세스가 죽지 않게 한다 (pg 는 처리기가 없으면 예외를 던진다).
  pool.on('error', (err) => console.error('[db] Postgres 연결 오류:', err.message))

  const q = async (client, sql, params) =>
    client.query(toPgPlaceholders(sql), (params ?? []).map(toPgValue))
  const make = (client) => ({
    dialect: 'postgres',
    get: async (sql, params) => (await q(client, sql, params)).rows[0],
    all: async (sql, params) => (await q(client, sql, params)).rows,
    run: async (sql, params) => ({ changes: (await q(client, sql, params)).rowCount ?? 0 }),
  })

  // 여러 인스턴스가 동시에 시작해도 스키마 생성이 겹치지 않게 잠근다.
  const setup = await pool.connect()
  try {
    await setup.query('SELECT pg_advisory_lock(727274)')
    await setup.query(PG_SCHEMA)
  } finally {
    await setup.query('SELECT pg_advisory_unlock(727274)').catch(() => {})
    setup.release()
  }

  const base = make(pool)
  return {
    ...base,
    async tx(fn) {
      const client = await pool.connect()
      try {
        await client.query('BEGIN')
        const result = await fn(make(client))
        await client.query('COMMIT')
        return result
      } catch (err) {
        await client.query('ROLLBACK').catch(() => {})
        throw err
      } finally {
        client.release()
      }
    },
    async close() {
      await pool.end()
    },
  }
}

// ---------------------------------------------------------------------------
// PGlite (테스트 전용: 메모리 Postgres)
// ---------------------------------------------------------------------------

async function createPgliteDb() {
  const { PGlite, types } = await import('@electric-sql/pglite')
  const lite = await PGlite.create({ parsers: { [types.INT8]: (v) => (v === null ? null : Number(v)) } })
  await lite.exec(PG_SCHEMA)
  const make = (conn) => ({
    dialect: 'postgres',
    get: async (sql, params) => (await conn.query(toPgPlaceholders(sql), normalizeParams(params))).rows[0],
    all: async (sql, params) => (await conn.query(toPgPlaceholders(sql), normalizeParams(params))).rows,
    run: async (sql, params) => ({
      changes: (await conn.query(toPgPlaceholders(sql), normalizeParams(params))).affectedRows ?? 0,
    }),
  })
  return {
    ...make(lite),
    tx: (fn) => lite.transaction((t) => fn(make(t))),
    close: () => lite.close(),
  }
}

