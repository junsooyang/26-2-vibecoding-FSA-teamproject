/**
 * @param {{ driver?: 'sqlite' | 'postgres' | 'pglite', path?: string, url?: string }} options
 */
export async function createDb(options) {
  if (options.driver === 'postgres') return createPostgresDb(options.url)
  if (options.driver === 'pglite') return createPgliteDb()
  return createSqliteDb(options.path)
}

/** 환경변수로 정해지는 기본 DB 설정 */
export function dbOptionsFromEnv() {
  if (DB_DRIVER === 'pglite') return { driver: 'pglite' }
  if (DATABASE_URL) return { driver: 'postgres', url: DATABASE_URL }
  return { driver: 'sqlite', path: DB_PATH }
}

/** 지금 쓰는 DB 를 사람이 읽기 좋게 (비밀번호 등은 드러내지 않음) */
export function describeDb(options = dbOptionsFromEnv()) {
  if (options.driver === 'pglite') return 'PGlite (메모리, 테스트용)'
  if (options.driver === 'postgres') {
    try {
      const u = new URL(options.url)
      return `Postgres (${u.hostname}:${u.port || 5432}${u.pathname})`
    } catch {
      return 'Postgres'
    }
  }
  return `SQLite (${options.path})`
}

let instance = null
function getInstance() {
  if (!instance) {
    instance = createDb(dbOptionsFromEnv())
    // 연결에 실패하면 다음 요청에서 다시 시도할 수 있게 비운다.
    instance.catch(() => {
      instance = null
    })
  }
  return instance
}

/** 프로세스 전체에서 함께 쓰는 DB. 첫 쿼리 때 연결하고 스키마를 만든다. */
export const db = {
  get: async (sql, params) => (await getInstance()).get(sql, params),
  all: async (sql, params) => (await getInstance()).all(sql, params),
  run: async (sql, params) => (await getInstance()).run(sql, params),
  tx: async (fn) => (await getInstance()).tx(fn),
  /** 연결·스키마 준비가 끝날 때까지 기다린다 (서버 시작 시 미리 확인용) */
  ready: async () => {
    await getInstance()
  },
  dialect: async () => (await getInstance()).dialect,
  async close() {
    if (!instance) return
    const current = instance
    instance = null
    try {
      await (await current).close()
    } catch {
      // 이미 닫혔거나 연결 실패
    }
  },
}
